	const Info &Get(int skill)
	{
		static const Info none{};
		return skill >= 0 && skill < Count ? Table[skill] : none;
	}

	int RacialLevel(uint16_t race, int skill)
	{
		switch (race) {
		case 4: case 112: return skill == 27 ? 50 : 0;           // forage
		case 6: case 77: case 98: return skill == 29 ? 50 : 0;   // hide
		case 8: case 94: return skill == 40 ? 50 : 0;            // sense heading
		case 11: case 81: return skill == 42 ? 50 : 0;           // sneak
		case 12: return skill == 57 ? 50 : 0;                    // tinkering
		case 128: return skill == 27 ? 50 : skill == 50 ? 100 : 0; // forage, swimming
		case 130: return skill == 39 || skill == 42 ? 50 : 0;    // safe fall, sneak
		default: return 0;
		}
	}

	int HasSkill(const ZoneProfile &me, int skill)
	{
		if (skill < 0 || skill >= Count)
			return 0;
		int racial = RacialLevel(me.race, skill);
		int value = me.skills[skill];
		const Info &info = Get(skill);
		int cls = me.class_id;
		if (value > 253 || cls < 1 || cls > Classes || info.cap[cls - 1] == 0)
			return racial;
		if (info.level[cls - 1] <= me.level)
			return value < 1 ? 1 : value;
		return value > 0 ? racial : 0;
	}
