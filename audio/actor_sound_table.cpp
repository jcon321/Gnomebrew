	ActorSounds SoundsForActor(uint16_t race, uint8_t gender, uint8_t texture, float height)
	{
		ActorSounds sounds;
		int tall = height > 10 ? 1 : 0;
		for (const Entry &entry : Entries) {
			if (entry.race != race || (entry.gender >= 0 && entry.gender != gender) ||
				(entry.texture >= 0 && entry.texture != (texture > 3 ? 0 : texture)) || (entry.tall >= 0 && entry.tall != tall))
				continue;
			for (int i = 0; i < ActorSounds::Count; ++i)
				sounds.slot[i] = Rows[entry.row][i];
			break;
		}
		return sounds;
	}
